// Embeds assets/ into src/bundled.ts so the worker can set up ~/orca-video-theme on a new
// machine (a worker cannot read its own plugin folder). assets/ stays the readable source.
//   node scripts/bundle-assets.mjs          rewrite src/bundled.ts
//   node scripts/bundle-assets.mjs --check  exit 1 if src/bundled.ts is out of date
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(root, 'assets')
const out = join(root, 'src', 'bundled.ts')

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

const entries = walk(assets).map((p) => [relative(assets, p).split('\\').join('/'), readFileSync(p, 'utf8')])
const body = entries.map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)}`).join(',\n')
const source =
  '// Generated by scripts/bundle-assets.mjs from assets/. Do not edit; edit assets/ and re-run it.\n' +
  `export const BUNDLED: Record<string, string> = {\n${body}\n}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(out, 'utf8') } catch {}
  if (current !== source) { console.error('src/bundled.ts is out of date: run node scripts/bundle-assets.mjs'); process.exit(1) }
  console.log('src/bundled.ts is up to date')
} else {
  writeFileSync(out, source, 'utf8')
  console.log(`wrote src/bundled.ts (${entries.length} files)`)
}
